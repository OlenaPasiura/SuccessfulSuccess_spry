"""AWS Lambda handler for sending weekly meeting CSV reports via Amazon SES."""

import json
import logging
import os
import sys
import urllib.parse
from email.message import EmailMessage
from typing import Any

import boto3


class ContextFormatter(logging.Formatter):
    """Custom logging formatter supporting extra fields in log output."""

    def format(self, record: logging.LogRecord) -> str:
        base_message = super().format(record)
        standard_keys = {
            "name",
            "msg",
            "args",
            "levelname",
            "levelno",
            "pathname",
            "filename",
            "module",
            "exc_info",
            "exc_text",
            "stack_info",
            "lineno",
            "funcName",
            "created",
            "msecs",
            "relativeCreated",
            "thread",
            "threadName",
            "processName",
            "process",
            "message",
            "asctime",
        }
        extra_fields = {k: v for k, v in record.__dict__.items() if k not in standard_keys}
        if extra_fields:
            try:
                return f"{base_message} | {json.dumps(extra_fields, default=str)}"
            except Exception:
                return f"{base_message} | {extra_fields}"
        return base_message


# Configure logger
log = logging.getLogger("report-mailer")
if not log.handlers:
    stream_handler = logging.StreamHandler(sys.stdout)
    stream_handler.setFormatter(
        ContextFormatter("%(asctime)s [%(levelname)s] %(name)s: %(message)s")
    )
    log.addHandler(stream_handler)
log.setLevel(os.getenv("LOG_LEVEL", "INFO").upper())


def handler(event: dict[str, Any] | None, context: Any = None) -> dict[str, Any]:
    """Lambda entry point for S3 ObjectCreated notifications to send reports via email."""
    if event is None:
        event = {}

    if not event.get("Records"):
        log.warning("No Records found in event", extra={"event": event})
        return {"statusCode": 400, "message": "No Records in event"}

    record = event["Records"][0]
    s3_info = record.get("s3", {})
    bucket = s3_info.get("bucket", {}).get("name", "")
    raw_key = s3_info.get("object", {}).get("key", "")
    key = urllib.parse.unquote_plus(raw_key)

    # Required log statement at execution start
    log.info(
        "report-mailer triggered",
        extra={"trigger": "s3_upload", "key": key},
    )

    if not bucket or not key:
        raise ValueError(f"Invalid S3 event: missing bucket ('{bucket}') or key ('{key}')")

    # Download CSV file from S3
    s3_client = boto3.client("s3")
    response = s3_client.get_object(Bucket=bucket, Key=key)
    csv_bytes = response["Body"].read()

    sender_email = os.getenv("SENDER_EMAIL", "reports@spry.org.ua")
    recipient_email = os.getenv("RECIPIENT_EMAIL", "pasiura.pn@ucu.edu.ua")
    verified_fallback = os.getenv("VERIFIED_SENDER_EMAIL", recipient_email)

    # Build MIME message with CSV attachment
    filename = os.path.basename(key)
    msg = EmailMessage()
    msg["Subject"] = f"Weekly Meeting Report: {filename}"
    msg["From"] = sender_email
    msg["To"] = recipient_email
    body_text = (
        f"Hello,\n\n"
        f"Please find attached the weekly meeting report ({filename}) "
        f"generated by the automated system.\n\n"
        f"Best regards,\nSuccessfulSuccess Team"
    )
    msg.set_content(body_text)
    msg.add_attachment(csv_bytes, maintype="text", subtype="csv", filename=filename)

    # Send email via Amazon SES SDK (sesv2)
    # IMPORTANT: Do NOT write or create new files in s3://<bucket>/reports/ to avoid infinite loops
    ses_client = boto3.client("sesv2")
    try:
        ses_response = ses_client.send_email(
            FromEmailAddress=sender_email,
            Destination={"ToAddresses": [recipient_email]},
            Content={"Raw": {"Data": msg.as_bytes()}},
        )
        message_id = ses_response.get("MessageId")
        log.info(
            "report-mailer sent email",
            extra={
                "message_id": message_id,
                "sender": sender_email,
                "recipient": recipient_email,
                "key": key,
            },
        )
    except Exception as exc:
        log.warning(
            f"SES email delivery attempted from {sender_email} but failed: {exc}",
            extra={"error": str(exc), "sender": sender_email, "recipient": recipient_email, "key": key},
        )
        # If domain identity is still pending DNS verification, fallback to verified sender
        if verified_fallback and verified_fallback != sender_email:
            try:
                log.info(f"Retrying email delivery with verified fallback sender: {verified_fallback}")
                msg.replace_header("From", verified_fallback)
                fallback_resp = ses_client.send_email(
                    FromEmailAddress=verified_fallback,
                    Destination={"ToAddresses": [recipient_email]},
                    Content={"Raw": {"Data": msg.as_bytes()}},
                )
                message_id = fallback_resp.get("MessageId")
                log.info(
                    "report-mailer sent email",
                    extra={
                        "message_id": message_id,
                        "sender": verified_fallback,
                        "recipient": recipient_email,
                        "key": key,
                    },
                )
            except Exception as fallback_exc:
                log.error(
                    f"SES fallback email delivery failed: {fallback_exc}",
                    extra={"error": str(fallback_exc), "sender": verified_fallback, "recipient": recipient_email},
                )

    return {
        "statusCode": 200,
        "bucket": bucket,
        "key": key,
        "bytes_count": len(csv_bytes),
    }
